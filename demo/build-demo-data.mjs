/* 组装档案（公共指标按档案复制，避免交叉污染） */
function assemble(P, commonLabs) {
  /* band 一律显式出现：有参考区间的给 [low, high]，没有的给 null。
     以前分类指标（倾倒症状/腹水等）干脆不写这个键，结果库里存成 NULL 之后
     读模型无法区分"没有区间"和"这个字段不存在"，parity 断言就会在 band 上来回抖。 */
  const metrics = [...P.extraMetrics, ...commonLabs()].map((m) => ({ ...m, color: KEY_COLOR[m.key] || m.color, band: m.band ?? null }));
  return { ...P.meta, path: P.path, molecular: P.molecular, hp: P.hp, lines: P.lines, cycles: P.cycles,
    perioperative: P.perioperative, resection: P.resection, mealLog: P.mealLog, dumping: P.dumping,
    supplements: P.supplements, peritoneal: P.peritoneal, endoscopy: P.endoscopy, rhythm: P.rhythm,
    viewpoints: P.viewpoints, metrics, events: P.events, docs: P.docs, candidates: P.candidates,
    pathology: P.pathology, activity: P.activity, familyTalk: P.familyTalk };
}

